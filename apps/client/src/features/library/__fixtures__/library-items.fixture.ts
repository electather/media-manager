function toItem(seed: Seed): LibraryItem {
  const item: LibraryItem = {
    id: `${seed.type}:${seed.slug}`,
    tmdbId: seed.slug,
    mediaType: seed.type,
    title: seed.title,
    year: seed.year,
    poster: poster(seed.slug),
    backdrop: backdrop(seed.slug),
    genres: seed.genres,
    rating: seed.rating,
    tags: seed.quality,
    status: "available",
    availability: {
      hasAnyServerCopy: true,
      requestEligible: false,
      servers: seed.servers.map((label) => ({ id: label.toLowerCase(), label })),
    },
  };
  if (seed.progress) {
    item.progress = { watched: seed.progress[0], total: seed.progress[1] };
  }
  return item;
}

